export function translate(lang: Lang, input: string): string {
  if (lang !== "ur" || !input) return input;
  const key = input.replace(/\s+/g, " ").trim();
  const hit = UR[key];
  if (hit) return hit;
  for (const [re, build] of PATTERNS) {
    const m = key.match(re);
    if (m) return build(m, (s) => translate(lang, s));
  }
  return input;
}

